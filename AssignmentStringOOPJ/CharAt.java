
public class CharAt {
	    public static void main(String[] args) {
	        String str = "Java Exercises!";
	        
	        // Retrieve characters at position 0 and 10
	        char index0 = str.charAt(0);
	        char index10 = str.charAt(10);
	        
	        // Display output
	        System.out.println("Original String = " + str);
	        System.out.println("The character at position 0 is " + index0);
	        System.out.println("The character at position 10 is " + index10);
	    }
	}



